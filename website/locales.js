function applyLocale(locale) {
  const language = locale === 'zh-CN' ? 'zh-CN' : 'en';
  document.documentElement.lang = language;
  for (const element of document.querySelectorAll('[data-i18n]')) {
    const entry = translations[element.dataset.i18n]; if (!entry) continue;
    for (const [index, pair] of Object.entries(entry.text)) {
      const node = element.childNodes[Number(index)]; if (node?.nodeType === 3) node.textContent = pair[language === 'en' ? 'en' : 'zh'];
    }
    for (const [name, pair] of Object.entries(entry.attrs)) element.setAttribute(name, pair[language === 'en' ? 'en' : 'zh']);
  }
  const button = document.querySelector('#language-switch');
  if (button) { button.textContent = language === 'en' ? '中文' : 'English'; button.lang = language === 'en' ? 'zh-CN' : 'en'; button.setAttribute('aria-label', language === 'en' ? 'Switch language to Chinese' : '切换为英文'); }
}
document.addEventListener('DOMContentLoaded', () => {
  let saved = 'en'; try { saved = localStorage.getItem('recdock.uiLanguage') || 'en'; } catch {}
  applyLocale(saved);
  document.querySelector('#language-switch').onclick = () => {
    const next = document.documentElement.lang === 'en' ? 'zh-CN' : 'en';
    try { localStorage.setItem('recdock.uiLanguage', next); } catch {}
    applyLocale(next);
  };
});
